/**
 * Android only: nothing RoadWise keeps on the phone leaves it through Android's backup or a phone
 * switch.
 *
 * `android.allowBackup: false` (app.config.ts) turns off cloud backup on every Android version and,
 * on Android 11 and lower, the device-to-device transfer too. On Android 12 and later the transfer to
 * a new phone (the setup wizard's cable or Wi-Fi copy) ignores allowBackup and follows
 * `android:dataExtractionRules` instead, and expo-secure-store's own rules there copy every
 * SharedPreferences file but its own: the drive detector's state, the capture state, the car link's
 * paired cars. Restored on a new phone those would describe a car, a parked spot and a drive that
 * phone never saw, and the SecureStore keys they sit beside never restore (their Keystore key stays
 * on the old phone).
 *
 * So this points both attributes at rules that exclude every domain, for cloud backup and for the
 * device transfer (`dataExtractionRules`, Android 12+) and for the older full backup
 * (`fullBackupContent`, Android 11 and lower, where allowBackup false already stops it: the two say
 * the same). The sign-in session, the store (`roadwise.db`), the journal (noBackupFilesDir, never
 * backed up anyway) and every preference stay on the phone they were made on; a driver signing in on
 * a new phone gets every synced drive back from the server. expo-secure-store's own rules are
 * switched off in app.config.ts (`configureAndroidBackup: false`), so the two never disagree.
 */
const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const BACKUP_RULES = 'roadwise_backup_rules';
const EXTRACTION_RULES = 'roadwise_data_extraction_rules';

/** Every storage domain Android's backup rules name (credential- and device-protected storage). */
const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external', 'device_root', 'device_file', 'device_database', 'device_sharedpref'];

const excludeAll = (indent) => DOMAINS.map((d) => `${indent}<exclude domain="${d}" path="." />`).join('\n');

/** Android 12+: nothing in a cloud backup, nothing in a transfer to a new phone. */
const EXTRACTION_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNoDataExtraction.js: nothing is backed up or moved to a new phone. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll('    ')}
  </cloud-backup>
  <device-transfer>
${excludeAll('    ')}
  </device-transfer>
</data-extraction-rules>
`;

/** Android 11 and lower (allowBackup false already stops it there): the same, nothing. */
const BACKUP_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNoDataExtraction.js: nothing is backed up. -->
<full-backup-content>
${excludeAll('  ')}
</full-backup-content>
`;

/** Points the application's backup attributes at the rules above; allowBackup stays false. */
function applyNoDataExtraction(manifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  app.$['android:allowBackup'] = 'false';
  app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
  app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
  return manifest;
}

const withAndroidNoDataExtraction = (config) => {
  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${BACKUP_RULES}.xml`), BACKUP_XML);
      fs.writeFileSync(path.join(dir, `${EXTRACTION_RULES}.xml`), EXTRACTION_XML);
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    applyNoDataExtraction(c.modResults);
    return c;
  });
};

module.exports = withAndroidNoDataExtraction;
module.exports.applyNoDataExtraction = applyNoDataExtraction;
module.exports.BACKUP_XML = BACKUP_XML;
module.exports.EXTRACTION_XML = EXTRACTION_XML;
module.exports.DOMAINS = DOMAINS;
